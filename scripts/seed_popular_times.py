DAY_MAP = ["mon","tue","wed","thu","fri","sat","sun"]

def classify_status(pop):
    if pop <= 40: return "여유"
    if pop <= 70: return "보통"
    return "혼잡"

def init_firebase():
    cred_env = os.getenv("FIREBASE_CREDENTIALS")
    if cred_env:
        cred_json = json.loads(base64.b64decode(cred_env).decode("utf-8"))
        cred = credentials.Certificate(cred_json)
    else:
        cred = credentials.Certificate("firebase_credentials.json")
    if not firebase_admin._apps:
        firebase_admin.initialize_app(cred)
    return firestore.client()

def main():
    logger.info("=== 혼잡도 업데이트 시작 ===")
    db = init_firebase()

    # 한국 시간 기준 현재 요일 + 시간
    kst = timezone(timedelta(hours=9))
    now = datetime.now(kst)
    day_key = DAY_MAP[now.weekday()]
    hour = now.hour
    logger.info(f"현재 시각: {now.strftime('%Y-%m-%d %H:%M')} KST ({day_key} {hour}시)")

    success = 0
    for cafe_id, data in POPULAR_TIMES.items():
        # cafes 컬렉션에 popular_times 저장 (최초 1회)
        db.collection("cafes").document(cafe_id).set({
            "name":         data["name"],
            "total_seats":  data["total_seats"],
            "naver_url":    data["naver_url"],
            "popular_times": {d: data[d] for d in DAY_MAP},
        }, merge=True)

        # 현재 시각 혼잡도 계산
        pop = data[day_key][hour]
        total = data["total_seats"]
        status = classify_status(pop)
        available = max(round(total * (1 - pop / 100)), 0)

        db.collection("occupancy").document(cafe_id).set({
            "current_popularity": pop,
            "status":             status,
            "available_seats":    available,
            "occupancy_rate":     round(pop / 100, 2),
            "fetched_at":         datetime.now(timezone.utc),
        })
        logger.info(f"[{data['name']}] {status} (혼잡도 {pop}, 가용 {available}/{total}석)")
        success += 1

    logger.info(f"=== 완료: {success}개 카페 업데이트 ===")

if __name__ == "__main__":
    main()
